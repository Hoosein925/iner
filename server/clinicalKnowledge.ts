/**
 * Generates concise official reference label for a skill based on Excel radif and category.
 * e.g. «مهارت شماره ۱۰ از مهارت‌های عمومی»
 */
export const getSkillReferenceLabel = (skill: {
  skillName?: string;
  name?: string;
  categoryName?: string;
  category?: string;
  radif?: number;
  referenceText?: string;
}): string => {
  if (skill.referenceText) return skill.referenceText;

  const rawCat = skill.categoryName || skill.category || '';
  let catLabel = 'مهارت‌های عمومی';
  if (rawCat.includes('تخصص') || rawCat.includes('اختصاص') || rawCat.includes('ویژه') || rawCat.includes('بالینی')) {
    catLabel = 'مهارت‌های تخصصی';
  } else if (rawCat.includes('ارتباط') || rawCat.includes('حقوق') || rawCat.includes('اخلاق')) {
    catLabel = 'مهارت‌های ارتباطی';
  } else if (rawCat.includes('عمومی')) {
    catLabel = 'مهارت‌های عمومی';
  } else if (rawCat) {
    catLabel = rawCat;
  }

  let radifNum = skill.radif;
  const fullName = skill.skillName || skill.name || '';
  if (!radifNum || radifNum <= 0) {
    const match = fullName.match(/^(?:مهارت\s*(?:شماره\s*)?)?([0-9۰-۹]+)[\s.\-_:)]+/);
    if (match) {
      radifNum = parseInt(match[1].replace(/[۰-۹]/g, d => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d))), 10);
    }
  }

  if (radifNum && radifNum > 0) {
    return `مهارت شماره ${radifNum} از ${catLabel}`;
  }

  return fullName ? `«${fullName}»` : 'مهارت بالینی';
};

/**
 * Organizes skills strictly based on the official Ahvaz University of Medical Sciences Nursing Directive:
 * 1. Red (<65%): Critical / High risk of patient harm - Immediate educational intervention
 * 2. Orange (65%-74%): Moderate / Needs training under head nurse supervision - Periodic training & shift evaluation
 * 3. Yellow (75%-84%): Growing / Good - Support and practice under supervision
 * 4. Green (>=85%): Safe & Autonomous / High quality - Certified competent & mentor role
 */
export function formatSkillsPercentageBreakdown(skills: SkillSummaryItem[]): {
  redSkills: SkillSummaryItem[];
  orangeSkills: SkillSummaryItem[];
  yellowSkills: SkillSummaryItem[];
  greenSkills: SkillSummaryItem[];
  // Backwards compatibility aliases
  criticalSkills: SkillSummaryItem[];
  warningSkills: SkillSummaryItem[];
  strongSkills: SkillSummaryItem[];
  summaryTable: string;
  inspectorAnalysisPrompt: string;
} {
  const sorted = [...(skills || [])].sort((a, b) => a.percentage - b.percentage);

  const redSkills = sorted.filter(s => s.percentage < 65);
  const orangeSkills = sorted.filter(s => s.percentage >= 65 && s.percentage < 75);
  const yellowSkills = sorted.filter(s => s.percentage >= 75 && s.percentage < 85);
  const greenSkills = sorted.filter(s => s.percentage >= 85);

  let summaryTable = `| ردیف | شماره سنجه در اکسل | سنجه / مهارت بالینی | حیطه مهارت | نمره (از ۴) | درصد | وضعیت و کد رنگی | اولویت اقدام اصلاحی |\n|:---:|:---:|:---|:---:|:---:|:---:|:---:|:---:|\n`;

  sorted.forEach((item, index) => {
    let colorStatus = '';
    let actionPriority = '';

    if (item.percentage < 65) {
      colorStatus = '🔴 قرمز (کمتر از ۶۵٪ - بحرانی)';
      actionPriority = 'مداخله فوری با آموزش و نظارت مستقیم';
    } else if (item.percentage < 75) {
      colorStatus = '🟠 نارنجی (۶۵٪ تا ۷۵٪ - متوسط)';
      actionPriority = 'آموزش دوره‌ای و ارزیابی در شیفت';
    } else if (item.percentage < 85) {
      colorStatus = '🟡 زرد (۷۵٪ تا ۸۵٪ - در حال رشد)';
      actionPriority = 'حمایت و تمرین تحت نظارت';
    } else {
      colorStatus = '🟢 سبز (۸۵٪ و بالاتر - ایمن و مسلط)';
      actionPriority = 'تایید صلاحیت و انتصاب به عنوان منتور';
    }

    const ref = item.referenceText || getSkillReferenceLabel(item);
    summaryTable += `| ${index + 1} | **${ref}** | ${item.skillName} | ${item.categoryName} | ${item.score} | ${item.percentage}٪ | ${colorStatus} | ${actionPriority} |\n`;
  });

  const inspectorAnalysisPrompt = `
📋 **گزارش آماری و داده‌های اولیه نمرات جهت دیپ سرچ هوش مصنوعی (Deep Search Context):**
- کل سنجه‌های پایش‌شده: ${sorted.length} مهارت
- 🔴 سنجه‌های قرمز (کمتر از ۶۵٪ - بحرانی و پرخطر برای بیمار): ${redSkills.length} مورد
- 🟠 سنجه‌های نارنجی (۶۵٪ تا ۷۴٪ - متوسط و نیازمند آموزش دوره‌ای): ${orangeSkills.length} مورد
- 🟡 سنجه‌های زرد (۷۵٪ تا ۸۴٪ - در حال رشد و نیازمند تمرین بیشتر): ${yellowSkills.length} مورد
- 🟢 سنجه‌های سبز (۸۵٪ و بالاتر - ایمن، مسلط و مستقل): ${greenSkills.length} مورد

توزیع کیفی میانگین‌ها:
- مهارت‌های دارای ضعف شدید (نمره ۱ یا ۲): ${sorted.filter(s => s.score < 3).length} مهارت
- مهارت‌های سطح استقلال و تسلط کامل (نمره ۳): ${sorted.filter(s => s.score >= 3 && s.score < 4).length} مهارت
- مهارت‌های سطح خبرگی و واجد شرایط مربی‌گری (نمره ۴): ${sorted.filter(s => s.score === 4).length} مهارت

تذکر بسیار مهم به هوش مصنوعی:
این داده‌ها صرفاً برای واکاوی عمیق (Deep Search) و کشف ریشه‌ای حوزه‌های ضعف در اختیار شما قرار گرفته است.
در خروجی نهایی به هیچ وجه جدول سنجه‌ها یا لیست مهارت‌ها را چاپ نکن و از تکرار متن مهارت‌ها اکیداً خودداری کن تا گزارش کاملاً خلوت، راهبردی و متمرکز بر اقدامات اصلاحی و برنامه آموزشی باشد.
`;

  return {
    redSkills,
    orangeSkills,
    yellowSkills,
    greenSkills,
    criticalSkills: redSkills,
    warningSkills: [...orangeSkills, ...yellowSkills],
    strongSkills: greenSkills,
    summaryTable,
    inspectorAnalysisPrompt,
  };
}


/**
 * Deduplicates and normalizes skill names
 */
function normalizeSkillName(name: string): string {
  return name
    .trim()
    .replace(/[«»""'']/g, '')
    .replace(/\s+/g, ' ')
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک');
}

